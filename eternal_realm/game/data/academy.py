"""The academy: the whole game taught chapter by chapter, in plain words a young player understands.

Lessons open one after another: a lesson is locked until every lesson before it is learned (only the group and city
lessons, which need a group or level 5, may be put off). Every lesson explains one thing, answers the questions a
new player usually has, asks the player to do it for real (open a screen, send a word, win a practice fight) and
notices by itself when it is done: a visit to one of its screens, a text command, or a fact in the database (a
``check``). Then it explains what just happened and pays a small reward.

The numbers in the answers are the game's own (``config.Balance`` and the data modules); keep them in step.
"""

from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True)
class Lesson:
    id: str
    chapter: int
    emoji: str
    title: str
    #: what the lesson teaches (a few short lines)
    teach: str
    #: what the player must do now
    task: str
    #: questions a new player usually has here, with short answers
    faq: tuple[tuple[str, str], ...] = ()
    #: the button that takes the player there: (label, screen, argument)
    go: tuple[str, str, str] | None = None
    #: a word the player sends instead (shown as «بنویس: …»)
    say: str = ""
    #: the word must be sent in a group, not in the private chat
    in_group: bool = False
    #: may be put off (it needs a group, a city, or something the hero may not have: gold, gear, an item); the others
    #: must be learned in order
    skippable: bool = False
    #: the game may refuse the deed itself (resting with full energy, say); trying it already teaches the lesson
    attempt: bool = False
    #: opening any of these screens (or sending any of these commands) completes the lesson
    visit: tuple[str, ...] = ()
    commands: tuple[str, ...] = ()
    #: a fact in the database that completes it (see ``AcademyService.CHECKS``)
    check: str = ""
    #: explained after it is done: what the player just saw
    after: str = ""
    gold: int = 200
    xp: int = 40


@dataclass(frozen=True)
class Chapter:
    number: int
    emoji: str
    name: str
    about: str
    #: the chest paid when every lesson of the chapter is done
    chest: str


