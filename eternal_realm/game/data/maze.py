def pool_for(floor: int) -> tuple[str, ...]:
    return next(foes for limit, foes in POOLS if floor <= limit)


def giant_tier(floor: int) -> str | None:
    """Who bars this floor: a giant every second or third floor, a harder one on every fifth, a guardian on every tenth."""
    if floor in BOSS_FLOORS:
        return "great"
    if floor % 5 == 0:
        return "elite"
    return "giant" if floor % 5 == 3 else None


def next_giant(floor: int) -> int:
    return next(f for f in range(floor, FLOORS + 1) if giant_tier(f))


def depth_level(floor: int) -> int:
    """The level the maze itself has on a floor: its foes are never weaker than this, whoever walks in."""
    if floor <= 30:
        return max(1, 2 * floor - 3)
    return round(57 + 1.5 * (floor - 30))  # the second half of the maze deepens more slowly


def foe_level(floor: int, hero_level: int) -> int:
    """A weak hero meets the maze's own strength (and must grow to pass); a strong one meets foes near their own level."""
    return max(depth_level(floor), round(hero_level * 0.9))


def giant_text(tier: str, floor: int, name: str) -> str:
    texts = GIANT_TEXT[tier]
    return texts[floor % len(texts)].format(name=name)


def floor_reward(floor: int) -> tuple[int, int]:
    """Base gold and experience of one floor (scaled by the hero's level)."""
    return 40 + 8 * floor, 50 + 9 * floor
