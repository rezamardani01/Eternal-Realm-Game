@dataclass(frozen=True)
class Outcome:
    weight: int
    text: str
    #: gold / xp: share of the floor's reward · heal / hurt: share of health · bless: a stat or "any" · curse · item ·
    #: lose: share of the gathered gold · fight: a foe attacks
    fx: dict


@dataclass(frozen=True)
class Choice:
    label: str
    outcomes: tuple[Outcome, ...]


@dataclass(frozen=True)
class Scene:
    id: str
    emoji: str
    title: str
    text: str
    choices: tuple[Choice, ...]


def _c(label: str, *outcomes: tuple[int, str, dict]) -> Choice:
    return Choice(label, tuple(Outcome(*o) for o in outcomes))


